// Target Machine Code Generator for Frontend (RISC-V RV32I and x86-64)

const RISCV_REGS = {
  R0: 't0', R1: 't1', R2: 't2', R3: 't3',
  R4: 't4', R5: 't5', R6: 'a0', R7: 'a1'
};

const X86_REGS = {
  R0: 'rax', R1: 'rcx', R2: 'rdx', R3: 'rsi',
  R4: 'rdi', R5: 'r8',  R6: 'r9',  R7: 'r10'
};

export function generateAssembly(instructions, allocResult, target = 'riscv') {
  if (target === 'riscv') {
    return emitRISCV(instructions, allocResult);
  } else {
    return emitX86(instructions, allocResult);
  }
}

function emitRISCV(instructions, allocResult) {
  const lines = [];
  const metrics = { loads: 0, stores: 0, instructions: 0, penaltyCycles: 0 };
  const alloc = allocResult.allocation;
  const numSpills = allocResult.numSpills;
  const stackSize = Math.max(16, ((numSpills * 4) + 15) & ~15);
  const spillOffsets = {};
  for (let i = 0; i < numSpills + 8; i++) {
    spillOffsets[`S${i}`] = i * 4;
  }

  lines.push({ text: `# --- Target: RISC-V RV32I Assembly (Generated by ChromaReg) ---`, type: 'comment' });
  lines.push({ text: `# Registers Allocated: ${allocResult.numRegistersUsed} | Memory Spills: ${numSpills} | Frame: ${stackSize}B`, type: 'comment' });
  lines.push({ text: `.globl main`, type: 'directive' });
  lines.push({ text: `.text`, type: 'directive' });
  lines.push({ text: `main:`, type: 'label' });
  lines.push({ text: `    addi sp, sp, -${stackSize}       # Prologue: allocate stack frame`, type: 'prologue' });
  metrics.instructions++;

  for (const inst of instructions) {
    lines.push({ text: `    # IR: ${inst.raw}`, type: 'ir-comment' });

    if (inst.op === 'LABEL') {
      lines.push({ text: `${inst.targetLabel}:`, type: 'label' });
      continue;
    }

    if (inst.op === 'RETURN') {
      const src = inst.src1;
      if (src) {
        const loc = alloc[src] || 'R0';
        if (loc.startsWith('R')) {
          const reg = RISCV_REGS[loc] || 't0';
          lines.push({ text: `    mv a0, ${reg}              # Return value to a0`, type: 'code' });
          metrics.instructions++;
        } else if (loc.startsWith('S')) {
          const off = spillOffsets[loc] || 0;
          lines.push({ text: `    lw a0, ${off}(sp)        # SPILL LOAD: return value from stack`, type: 'spill-load' });
          metrics.loads++;
          metrics.instructions++;
        } else {
          lines.push({ text: `    li a0, ${src}              # Immediate return`, type: 'code' });
          metrics.instructions++;
        }
      }
      lines.push({ text: `    addi sp, sp, ${stackSize}        # Epilogue: free stack frame`, type: 'epilogue' });
      lines.push({ text: `    ret`, type: 'epilogue' });
      metrics.instructions += 2;
      continue;
    }

    if (inst.op === 'GOTO') {
      lines.push({ text: `    j ${inst.targetLabel}`, type: 'branch' });
      metrics.instructions++;
      continue;
    }

    if (inst.op === 'IF_GOTO') {
      const condVar = inst.src1;
      const loc = alloc[condVar] || 'R0';
      let condReg = 't6';
      if (loc.startsWith('R')) {
        condReg = RISCV_REGS[loc] || 't0';
      } else if (loc.startsWith('S')) {
        const off = spillOffsets[loc] || 0;
        lines.push({ text: `    lw t6, ${off}(sp)        # SPILL RELOAD for branch test`, type: 'spill-load' });
        metrics.loads++;
        metrics.instructions++;
      }
      lines.push({ text: `    bnez ${condReg}, ${inst.targetLabel}`, type: 'branch' });
      metrics.instructions++;
      continue;
    }

    // Binary / Copy arithmetic
    const dest = inst.dest;
    const destLoc = alloc[dest] || 'R0';
    const isDestSpill = destLoc.startsWith('S');
    const destReg = isDestSpill ? 't6' : (RISCV_REGS[destLoc] || 't0');

    let src1Reg = 't1';
    if (inst.src1) {
      if (/^-?\d+$/.test(inst.src1)) {
        lines.push({ text: `    li t1, ${inst.src1}`, type: 'code' });
        metrics.instructions++;
      } else {
        const s1Loc = alloc[inst.src1] || 'R0';
        if (s1Loc.startsWith('R')) {
          src1Reg = RISCV_REGS[s1Loc] || 't1';
        } else if (s1Loc.startsWith('S')) {
          const off = spillOffsets[s1Loc] || 0;
          lines.push({ text: `    lw t1, ${off}(sp)        # SPILL LOAD: reload ${inst.src1}`, type: 'spill-load' });
          metrics.loads++;
          metrics.instructions++;
        }
      }
    }

    let src2Reg = 't2';
    if (inst.src2) {
      if (/^-?\d+$/.test(inst.src2)) {
        lines.push({ text: `    li t2, ${inst.src2}`, type: 'code' });
        metrics.instructions++;
      } else {
        const s2Loc = alloc[inst.src2] || 'R0';
        if (s2Loc.startsWith('R')) {
          src2Reg = RISCV_REGS[s2Loc] || 't2';
        } else if (s2Loc.startsWith('S')) {
          const off = spillOffsets[s2Loc] || 0;
          lines.push({ text: `    lw t2, ${off}(sp)        # SPILL LOAD: reload ${inst.src2}`, type: 'spill-load' });
          metrics.loads++;
          metrics.instructions++;
        }
      }
    }

    if (inst.op === 'COPY') {
      if (destReg !== src1Reg) {
        lines.push({ text: `    mv ${destReg}, ${src1Reg}`, type: 'code' });
        metrics.instructions++;
      }
    } else {
      const opMap = { '+': 'add', '-': 'sub', '*': 'mul', '/': 'div', '<': 'slt' };
      const mOp = opMap[inst.op] || 'add';
      lines.push({ text: `    ${mOp} ${destReg}, ${src1Reg}, ${src2Reg}`, type: 'code' });
      metrics.instructions++;
    }

    if (isDestSpill) {
      const off = spillOffsets[destLoc] || 0;
      lines.push({ text: `    sw ${destReg}, ${off}(sp)        # SPILL STORE: save ${dest} to ${destLoc}`, type: 'spill-store' });
      metrics.stores++;
      metrics.instructions++;
    }
  }

  metrics.penaltyCycles = (metrics.loads + metrics.stores) * 5;
  return { lines, metrics, target: 'RISC-V RV32I' };
}

function emitX86(instructions, allocResult) {
  const lines = [];
  const metrics = { loads: 0, stores: 0, instructions: 0, penaltyCycles: 0 };
  const alloc = allocResult.allocation;
  const numSpills = allocResult.numSpills;
  const stackSize = Math.max(16, ((numSpills * 8) + 15) & ~15);
  const spillOffsets = {};
  for (let i = 0; i < numSpills + 8; i++) {
    spillOffsets[`S${i}`] = i * 8;
  }

  lines.push({ text: `; --- Target: x86-64 Intel Syntax (Generated by ChromaReg) ---`, type: 'comment' });
  lines.push({ text: `; Registers Allocated: ${allocResult.numRegistersUsed} | Memory Spills: ${numSpills} | Frame: ${stackSize}B`, type: 'comment' });
  lines.push({ text: `.intel_syntax noprefix`, type: 'directive' });
  lines.push({ text: `.globl main`, type: 'directive' });
  lines.push({ text: `main:`, type: 'label' });
  lines.push({ text: `    sub rsp, ${stackSize}             ; Prologue: allocate stack frame`, type: 'prologue' });
  metrics.instructions++;

  for (const inst of instructions) {
    lines.push({ text: `    ; IR: ${inst.raw}`, type: 'ir-comment' });

    if (inst.op === 'LABEL') {
      lines.push({ text: `${inst.targetLabel}:`, type: 'label' });
      continue;
    }

    if (inst.op === 'RETURN') {
      const src = inst.src1;
      if (src) {
        const loc = alloc[src] || 'R0';
        if (loc.startsWith('R')) {
          const reg = X86_REGS[loc] || 'rax';
          if (reg !== 'rax') {
            lines.push({ text: `    mov rax, ${reg}`, type: 'code' });
            metrics.instructions++;
          }
        } else if (loc.startsWith('S')) {
          const off = spillOffsets[loc] || 0;
          lines.push({ text: `    mov rax, [rsp+${off}]     ; SPILL LOAD: return value`, type: 'spill-load' });
          metrics.loads++;
          metrics.instructions++;
        }
      }
      lines.push({ text: `    add rsp, ${stackSize}             ; Epilogue`, type: 'epilogue' });
      lines.push({ text: `    ret`, type: 'epilogue' });
      metrics.instructions += 2;
      continue;
    }

    if (inst.op === 'GOTO') {
      lines.push({ text: `    jmp ${inst.targetLabel}`, type: 'branch' });
      metrics.instructions++;
      continue;
    }

    const dest = inst.dest;
    const destLoc = alloc[dest] || 'R0';
    const isDestSpill = destLoc.startsWith('S');
    const destReg = isDestSpill ? 'r11' : (X86_REGS[destLoc] || 'rax');

    if (inst.op === 'COPY') {
      if (/^-?\d+$/.test(inst.src1)) {
        lines.push({ text: `    mov ${destReg}, ${inst.src1}`, type: 'code' });
        metrics.instructions++;
      } else {
        const sLoc = alloc[inst.src1] || 'R0';
        const sReg = sLoc.startsWith('R') ? (X86_REGS[sLoc] || 'rcx') : 'r10';
        if (sLoc.startsWith('S')) {
          lines.push({ text: `    mov r10, [rsp+${spillOffsets[sLoc] || 0}] ; SPILL LOAD`, type: 'spill-load' });
          metrics.loads++;
          metrics.instructions++;
        }
        if (destReg !== sReg) {
          lines.push({ text: `    mov ${destReg}, ${sReg}`, type: 'code' });
          metrics.instructions++;
        }
      }
    } else {
      const opName = inst.op === '+' ? 'add' : (inst.op === '-' ? 'sub' : 'imul');
      lines.push({ text: `    ${opName} ${destReg}, ${inst.src2}`, type: 'code' });
      metrics.instructions++;
    }

    if (isDestSpill) {
      const off = spillOffsets[destLoc] || 0;
      lines.push({ text: `    mov [rsp+${off}], ${destReg}      ; SPILL STORE: save ${dest}`, type: 'spill-store' });
      metrics.stores++;
      metrics.instructions++;
    }
  }

  metrics.penaltyCycles = (metrics.loads + metrics.stores) * 5;
  return { lines, metrics, target: 'x86-64 Intel' };
}
